import { chromium } from 'playwright-core';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const directory=new URL('../artifacts/',import.meta.url);
await mkdir(directory,{recursive:true});
const base=process.env.FRONT_URL||'http://127.0.0.1:5173';
const live=JSON.parse(await readFile(new URL('../../output/live_conversations_report.json',import.meta.url),'utf8'));
assert.equal(live.passed,true,'先运行 python -m scripts.check_live_conversations');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const report={source:'真实服务器会话',page_errors:[]};
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 await context.addInitScript(id=>localStorage.setItem('jc.ui.v2',JSON.stringify({active:id,mode:'chat'})),live.conversation_id);
 const page=await context.newPage();
 page.on('pageerror',e=>report.page_errors.push(e.message));
 let chatRequests=0;page.on('request',r=>{if(r.url().endsWith('/api/chat'))chatRequests++;});
 await page.goto(base);
 await page.getByText('较早内容已整理为摘要 · 查看摘要',{exact:true}).waitFor();
 assert.ok(await page.locator('.message.assistant').count()>=8);
 await page.screenshot({path:new URL('conversations-desktop.png',directory).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
 await page.getByText('较早内容已整理为摘要 · 查看摘要',{exact:true}).click();
 await page.getByRole('dialog',{name:'对话摘要'}).waitFor();
 assert.ok((await page.locator('.original-text').innerText()).includes('松林计划'));
 await page.screenshot({path:new URL('conversations-summary.png',directory).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
 await page.keyboard.press('Escape');
 await page.locator('.inline-cite').first().click();await page.getByRole('dialog',{name:'参考原文'}).waitFor();
 assert.ok((await page.locator('.original-text').innerText()).length>0);
 await page.keyboard.press('Escape');
 await page.reload();await page.getByText('较早内容已整理为摘要 · 查看摘要',{exact:true}).waitFor();
 const input=page.getByLabel('输入问题');await input.fill('输入法交互测试');
 await input.dispatchEvent('keydown',{key:'Enter',code:'Enter',isComposing:true});
 await input.press('Shift+Enter');assert.equal(chatRequests,0);await input.fill('');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.getByText('较早内容已整理为摘要 · 查看摘要',{exact:true}).click();
 assert.equal(await page.locator('dialog').evaluate(d=>Math.round(d.getBoundingClientRect().width)),390);
 await page.screenshot({path:new URL('conversations-mobile.png',directory).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
 await page.keyboard.press('Escape');
 const other=await browser.newContext();
 const page2=await other.newPage();await page2.goto(base);
 const response=await page2.request.get(`${base}/api/conversations/${live.conversation_id}`);
 assert.equal(response.status(),200);assert.ok((await response.json()).data.length>=8);
 report.shared_history='passed';report.summary='passed';report.citation='passed';report.mobile='passed';report.refresh='passed';
 assert.deepEqual(report.page_errors,[]);
} finally {
 await writeFile(new URL('conversations-browser-report.json',directory),JSON.stringify(report,null,2));
 await browser.close();
}
console.log(JSON.stringify(report));
